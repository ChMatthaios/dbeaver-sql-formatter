MERGE INTO REPORTING.CUSTOMER_SUMMARY T
USING (
  WITH BASE_ORDERS AS (
    SELECT O.CUSTOMER_ID,
           O.ORDER_ID,
           O.ORDER_DATE,
           O.STATUS_CODE,
           O.TOTAL_AMOUNT,
           ROW_NUMBER() OVER (PARTITION BY O.CUSTOMER_ID ORDER BY O.ORDER_DATE DESC, O.ORDER_ID DESC) AS RN
      FROM ORDER_HEADER O
     WHERE O.ORDER_DATE >= CURRENT DATE - 365 DAYS
  ),
  CUSTOMER_AGG AS (
    SELECT BO.CUSTOMER_ID,
           COUNT(*) AS ORDER_COUNT,
           SUM(BO.TOTAL_AMOUNT) AS TOTAL_AMOUNT,
           AVG(BO.TOTAL_AMOUNT) AS AVG_AMOUNT,
           MAX(BO.ORDER_DATE) AS LAST_ORDER_DATE
      FROM BASE_ORDERS BO
     GROUP BY BO.CUSTOMER_ID
  )
  SELECT C.CUSTOMER_ID,
         C.CUSTOMER_NAME,
         C.COUNTRY_CODE,
         CA.ORDER_COUNT,
         CA.TOTAL_AMOUNT,
         CA.AVG_AMOUNT,
         CA.LAST_ORDER_DATE,
         CASE
           WHEN CA.TOTAL_AMOUNT >= 25000 THEN 'PLATINUM'
           WHEN CA.TOTAL_AMOUNT >= 10000 THEN 'VIP'
           WHEN CA.TOTAL_AMOUNT >= 5000 THEN 'GOLD'
           ELSE 'STANDARD'
         END AS CUSTOMER_SEGMENT
    FROM CUSTOMER C
    INNER JOIN CUSTOMER_AGG CA ON CA.CUSTOMER_ID = C.CUSTOMER_ID
    LEFT JOIN BASE_ORDERS BO ON BO.CUSTOMER_ID = C.CUSTOMER_ID AND BO.RN = 1
   WHERE C.IS_ACTIVE = 1
) S
ON T.CUSTOMER_ID = S.CUSTOMER_ID
WHEN MATCHED THEN
  UPDATE SET T.CUSTOMER_NAME = S.CUSTOMER_NAME,
             T.COUNTRY_CODE = S.COUNTRY_CODE,
             T.ORDER_COUNT = S.ORDER_COUNT,
             T.TOTAL_AMOUNT = S.TOTAL_AMOUNT,
             T.AVG_AMOUNT = S.AVG_AMOUNT,
             T.LAST_ORDER_DATE = S.LAST_ORDER_DATE,
             T.CUSTOMER_SEGMENT = S.CUSTOMER_SEGMENT
WHEN NOT MATCHED THEN
  INSERT (CUSTOMER_ID, CUSTOMER_NAME, COUNTRY_CODE, ORDER_COUNT, TOTAL_AMOUNT, AVG_AMOUNT, LAST_ORDER_DATE, CUSTOMER_SEGMENT)
  VALUES (S.CUSTOMER_ID, S.CUSTOMER_NAME, S.COUNTRY_CODE, S.ORDER_COUNT, S.TOTAL_AMOUNT, S.AVG_AMOUNT, S.LAST_ORDER_DATE, S.CUSTOMER_SEGMENT);
